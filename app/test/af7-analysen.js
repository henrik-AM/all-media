const assert=require('node:assert/strict');const A=require('../../gemeinsam/analyse');
let n=0;const t=(name,fn)=>{fn();console.log(`OK ${++n} ${name}`)};
const fenster=tage=>({tage,reichweite:20,aufrufe:40,followerAufrufe:15,nichtFollowerAufrufe:25,sichtzeitMs:120000,interaktionen:3,laender:[{land:'Deutschland',ab:10},{land:'Kleine Gruppe',ab:9}],beitraege:[{id:'p',titel:'Beitrag',aufrufe:40,reichweite:20}]});
const daten={seit:'2026-10-26T00:00:00Z',zeitraeume:[fenster(7),fenster(30)]};
const rows=A.zeilen(daten);
t('beide Zeitfenster',()=>assert.equal(rows.filter(r=>r.text.includes('UTC-Kalendertage')).length,2));
t('erreichte Konten',()=>assert.equal(rows.find(r=>r.text.startsWith('Reichweite')).neben,'20'));
